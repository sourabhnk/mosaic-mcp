def parse_request_id(raw: "str | int") -> tuple[str, int] | None:
    """('dossier' | 'audit', n) for 'dossier-12' / 'audit-3', else None.

    A bare number is None on purpose: dossier and audit ids are two separate
    sequences, so 12 names two requests and neither is guessed."""
    if isinstance(raw, bool) or not isinstance(raw, str):
        return None
    kind, _, n = raw.strip().lower().partition("-")
    if kind not in RESULT_KINDS or not n.isdigit() or int(n) < 1:
        return None
    return kind, int(n)


def result_id(kind: str, n: int) -> str:
    """The request_id a client is given, and polls with."""
    if kind not in RESULT_KINDS:
        raise ValueError(kind)
    return f"{kind}-{int(n)}"
